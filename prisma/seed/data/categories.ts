/**
 * The category tree, modelled on IndiaMART's top-level categories and their
 * principal subcategories (decision D34). Two levels for most trades, three
 * where the seeded catalogue already used them (lighting, cables, steel).
 *
 * Rules:
 *   - slugs are GLOBALLY unique (the seed's slug→id map and the discovery
 *     routes both assume it), so generic words are qualified: "led-lighting"
 *     not "lighting" under a second parent.
 *   - names are what an Indian B2B seller calls the trade, not a taxonomy
 *     term. Sellers pick from this list at registration; if a seller cannot
 *     find themselves in it, the list is wrong, not the seller.
 *   - the first four roots and their children keep the slugs the product
 *     fixtures (prisma/seed/catalog.ts, leads.ts) reference.
 */

